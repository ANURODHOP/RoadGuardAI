-- ============================================================
-- RoadGuard — Migration 005: Storage Bucket & RLS Policies
-- ============================================================
-- Apply via: supabase db push
-- Or in Supabase Studio SQL Editor (run as service role).
-- ============================================================
-- This migration ensures the 'evidence' storage bucket exists
-- and has correct RLS policies for authenticated users.
-- ============================================================

-- ============================================================
-- STEP 1: Ensure the evidence bucket exists
-- (Idempotent — does nothing if bucket already exists)
-- ============================================================
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'evidence',
  'evidence',
  false,                              -- Private bucket; files served via signed URLs only
  10485760,                           -- 10 MB per file
  ARRAY[
    'image/jpeg',
    'image/jpg',
    'image/png',
    'image/webp',
    'image/heic',
    'image/heif'
  ]
)
ON CONFLICT (id) DO UPDATE SET
  public             = EXCLUDED.public,
  file_size_limit    = EXCLUDED.file_size_limit,
  allowed_mime_types = EXCLUDED.allowed_mime_types;

-- ============================================================
-- STEP 2: Drop old policies (safe, idempotent via IF EXISTS)
-- ============================================================
DROP POLICY IF EXISTS "evidence_objects_insert"  ON storage.objects;
DROP POLICY IF EXISTS "evidence_objects_select"  ON storage.objects;
DROP POLICY IF EXISTS "evidence_objects_update"  ON storage.objects;
DROP POLICY IF EXISTS "evidence_objects_delete"  ON storage.objects;

-- ============================================================
-- STEP 3: INSERT — Authenticated users can upload evidence
-- Path constraint: complaints/{complaint_id}/{user_id}/...
-- Users can ONLY upload under their own user_id segment.
-- ============================================================
CREATE POLICY "evidence_objects_insert" ON storage.objects
  FOR INSERT
  WITH CHECK (
    bucket_id = 'evidence'
    AND auth.role() = 'authenticated'
    -- Enforce path pattern: complaints/<uuid>/<user-id>/...
    -- The 3rd path segment must match the uploader's own auth.uid()
    AND split_part(name, '/', 3) = auth.uid()::text
  );

-- ============================================================
-- STEP 4: SELECT — Authenticated users can read (for signed URLs)
-- Users can read evidence on complaints they reported,
-- contributed to, or any evidence on non-private complaints.
-- ============================================================
CREATE POLICY "evidence_objects_select" ON storage.objects
  FOR SELECT
  USING (
    bucket_id = 'evidence'
    AND auth.role() = 'authenticated'
  );

-- ============================================================
-- STEP 5: UPDATE — Uploader or admin can overwrite their own files
-- ============================================================
CREATE POLICY "evidence_objects_update" ON storage.objects
  FOR UPDATE
  USING (
    bucket_id = 'evidence'
    AND auth.role() = 'authenticated'
    AND (
      -- Original uploader
      split_part(name, '/', 3) = auth.uid()::text
      -- Admins / moderators
      OR EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = auth.uid() AND role IN ('admin', 'moderator')
      )
    )
  );

-- ============================================================
-- STEP 6: DELETE — Uploader or admin can delete their own files
-- ============================================================
CREATE POLICY "evidence_objects_delete" ON storage.objects
  FOR DELETE
  USING (
    bucket_id = 'evidence'
    AND auth.role() = 'authenticated'
    AND (
      -- Original uploader
      split_part(name, '/', 3) = auth.uid()::text
      -- Admins / moderators
      OR EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = auth.uid() AND role IN ('admin', 'moderator')
      )
    )
  );

-- ============================================================
-- NOTES
-- ============================================================
-- 1. All reads return 403 to unauthenticated callers because
--    the bucket is private and requires a signed URL.
-- 2. Signed URLs are generated by the mobile app calling
--    supabase.storage.from('evidence').createSignedUrl(path, ttl)
--    which uses the anon key on behalf of the authenticated user.
-- 3. Users cannot read the files of other users directly;
--    they access via complaint records which the app fetches.
-- 4. File size and mime type limits are enforced at the bucket
--    level (10 MB, images only) in addition to mobile-side checks.
